"""Pydantic v2 schemas for the Custom 3-Tier Cognitive Memory Engine."""

from datetime import UTC, datetime
from enum import StrEnum
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field


class MemoryStatus(StrEnum):
    """Lifecycle status of a Temporal Semantic Memory record."""

    ACTIVE = "ACTIVE"
    SUPERSEDED = "SUPERSEDED"


class TemporalFactRecord(BaseModel):
    """Tier 2: Temporal Semantic Memory schema with non-destructive conflict resolution support."""

    model_config = ConfigDict(extra="forbid")

    memory_id: str = Field(
        default_factory=lambda: f"mem_{uuid4().hex[:8]}",
        description="Unique identifier for the memory record",
    )
    entity: str = Field(..., description="Canonical entity identifier (e.g., FPT_Corporation)")
    attribute: str = Field(..., description="Normalized attribute key (e.g., AI_Capex_Investment)")
    value: str = Field(..., description="Verified factual statement or value")
    valid_from: str = Field(
        ...,
        description="ISO-8601 date (YYYY-MM-DD) when the fact became effective",
    )
    valid_to: str | None = Field(
        default=None,
        description="ISO-8601 date (YYYY-MM-DD) when the fact was superseded; None if currently ACTIVE",
    )
    status: MemoryStatus = Field(
        default=MemoryStatus.ACTIVE,
        description="ACTIVE if current; SUPERSEDED if replaced by a newer conflicting fact",
    )
    source_chunk_id: str = Field(
        ...,
        description="Deterministic citation ID verified by the Anti-Poisoning Gate",
    )
    confidence_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Verified groundedness score in [0.0, 1.0]",
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat(),
        description="UTC timestamp when this record was committed",
    )


class EpisodicLogRecord(BaseModel):
    """Tier 3a: Episodic Memory record capturing the execution trace of a completed research session."""

    model_config = ConfigDict(extra="forbid")

    episode_id: str = Field(
        default_factory=lambda: f"ep_{uuid4().hex[:8]}",
        description="Unique identifier for the episodic trace",
    )
    session_id: str = Field(..., description="Session identifier")
    user_query: str = Field(..., description="Original complex research query")
    decomposed_sub_queries: list[str] = Field(
        default_factory=list,
        description="Sub-queries generated by the Planner",
    )
    verified_chunk_ids: list[str] = Field(
        default_factory=list,
        description="Source chunk IDs that passed verification",
    )
    total_tokens_used: int = Field(default=0, ge=0)
    success: bool = Field(default=True, description="Whether the research converged successfully")
    lessons_learned: str = Field(
        default="",
        description="Post-session reflection on effective query formulation and retrieval sources",
    )
    timestamp: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


class ProceduralRule(BaseModel):
    """Tier 3b: Procedural Memory strategy rule distilled from past episodes and injected at session start."""

    model_config = ConfigDict(extra="forbid")

    rule_id: str = Field(
        default_factory=lambda: f"rule_{uuid4().hex[:8]}",
        description="Unique identifier for the procedural rule",
    )
    domain_pattern: str = Field(
        ...,
        description="Topic or query pattern where this rule applies (e.g., financial_capex_comparison)",
    )
    strategy_instruction: str = Field(
        ...,
        description="Actionable retrieval or decomposition rule injected into the Planner prompt",
    )
    usage_count: int = Field(default=0, ge=0)
    effectiveness_score: float = Field(default=1.0, ge=0.0, le=1.0)
